#!/usr/bin/env node
// Regenerates assets/schemes/<scheme>.json from packages/ui/src/styles/tokens.css, as the browser resolves it
// (oklch() and color-mix() included), so the Rune theme and the web package can't drift apart.
//
// usage: node rune/theme/tools/theme.mjs           writes the files
//        node rune/theme/tools/theme.mjs --check   fails if they're out of date (CI)
//
// Needs Playwright with Chromium (`bunx playwright install chromium`), or CHROMIUM_PATH set to a Chromium binary.

import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const tokensCss = resolve(here, "../../../packages/ui/src/styles/tokens.css");
const schemesJs = resolve(here, "../../../packages/ui/src/theme/schemes.js");
const out = resolve(here, "../assets/schemes");
const check = process.argv.includes("--check");

const css = readFileSync(tokensCss, "utf8");
const schemes = [
  ...readFileSync(schemesJs, "utf8")
    .match(/colorSchemes = \[([^\]]*)\]/)[1]
    .matchAll(/"(\w+)"/g),
].map((m) => m[1]);
const rootBody = css.slice(
  css.indexOf(":root {"),
  css.indexOf("}", css.indexOf(":root {")),
);
const tokens = [...rootBody.matchAll(/(--[\w-]+)\s*:/g)].map((m) => m[1]);
const numberTokens = ["--radius", "--radius-lg"];
const colorTokens = tokens.filter(
  (t) => !numberTokens.includes(t) && !t.startsWith("--font-"),
);

const require = createRequire(import.meta.url);
const { chromium } = require("playwright");
// CHROMIUM_PATH picks a browser other than the one Playwright installed (as Rune's own scripts allow).
const browser = await chromium.launch({
  executablePath: process.env.CHROMIUM_PATH || undefined,
});
const page = await browser.newPage();
await page.setContent(`<!doctype html><style>${css}</style><body></body>`);

let stale = false;
for (const scheme of schemes) {
  const theme = {
    name: scheme[0].toUpperCase() + scheme.slice(1),
    about: "Generated by tools/theme.mjs from tokens.css; don't edit.",
  };
  for (const mode of ["light", "dark"]) {
    theme[mode] = await page.evaluate(
      ({ scheme, mode, colorTokens }) => {
        const html = document.documentElement;
        html.dataset.theme = mode;
        if (scheme === "stacks") delete html.dataset.colorScheme;
        else html.dataset.colorScheme = scheme;
        const canvas = document.createElement("canvas");
        canvas.width = canvas.height = 1;
        const ctx = canvas.getContext("2d", { willReadFrequently: true });
        const probe = document.createElement("div");
        document.body.append(probe);
        const hex = (value) => {
          ctx.clearRect(0, 0, 1, 1);
          ctx.fillStyle = "rgba(0,0,0,0)";
          ctx.fillStyle = value;
          ctx.fillRect(0, 0, 1, 1);
          const [r, g, b, a] = ctx.getImageData(0, 0, 1, 1).data;
          const parts = a === 255 ? [r, g, b] : [r, g, b, a];
          return (
            "#" + parts.map((v) => v.toString(16).padStart(2, "0")).join("")
          );
        };
        const result = {};
        for (const token of colorTokens) {
          probe.style.color = `var(${token})`;
          result[token.slice(2)] = hex(getComputedStyle(probe).color);
        }
        probe.remove();
        return result;
      },
      { scheme, mode, colorTokens },
    );
  }
  theme.numbers = {};
  for (const token of numberTokens) {
    theme.numbers[token.slice(2)] = parseFloat(
      rootBody.match(new RegExp(`${token}:\\s*([\\d.]+)px`))[1],
    );
  }
  const file = resolve(out, `${scheme}.json`);
  const json = JSON.stringify(theme, null, 2) + "\n";
  if (check) {
    let current = "";
    try {
      current = readFileSync(file, "utf8");
    } catch {}
    if (current !== json) {
      console.error(
        `${file} is out of date with tokens.css; run tools/theme.mjs`,
      );
      stale = true;
    }
  } else {
    writeFileSync(file, json);
  }
}
await browser.close();
if (stale) process.exit(1);
